# ============================================================================
#  CPM（循環成分）による非対称MDS
#
#  上から下へ順に読める形で書いてある。関数にまとめていない。
#  冗長だが、どの行が何をしているかを追えることを優先している。
#
#  前提：data/fdi_2023_oecd.csv（このリポジトリに同梱）
#        （OECD 対外直接投資ポジション 2023年末、行=投資国、列=投資先、単位=10億米ドル）
#  必要：install.packages(c("ggplot2", "ggrepel"))
# ============================================================================

library(ggplot2)
library(ggrepel)


# ============================================================================
#  1. データを行列にする
# ============================================================================

fdi <- read.csv("data/fdi_2023_oecd.csv", fileEncoding = "UTF-8-BOM")
rownames(fdi) <- fdi$country
T <- data.matrix(fdi[, -1])     # 1列目（国名）を除く

diag(T) <- NA                   # 自国に対する値は無い

nm <- rownames(T)
n  <- nrow(T)                   # 8

print(T)                        # 単位は10億米ドル


# ============================================================================
#  2. 投資額を非類似度に変換し、歪対称成分を取り出す
# ============================================================================
#     δ_ij = -log(T_ij)
#
# 歪対称成分 A は非類似度への加法定数に不変なので、対数変換でよい。
# 循環成分 C は A の線形変換なので同じ不変性をもつ。

Delta <- -log(T)
diag(Delta) <- 0

A <- (Delta - t(Delta)) / 2


# ============================================================================
#  3. 勾配成分と循環成分に分ける
# ============================================================================
#     φ_i   = (1/n) Σ_j a_ij       各対象の全体的な傾き
#     G_ij  = φ_i - φ_j            勾配で説明される分
#     C     = A - G                循環残差

phi <- rowSums(A) / n

cat("勾配 φ\n")
print(round(sort(phi), 3))

G <- outer(phi, phi, "-")

C <- A - G
diag(C) <- 0

# C の2つの性質を確認する
cat("\nC は歪対称か   :", all(abs(C + t(C)) < 1e-10), "\n")
cat("C の行和はゼロか :", all(abs(rowSums(C)) < 1e-10), "\n")

# 平方和の分け前（A のうちどれだけが勾配で、どれだけが循環か）
ss_A <- sum(A^2); ss_G <- sum(G^2); ss_C <- sum(C^2)
cat(sprintf("平方和  A = %.3f = G %.3f (%.1f%%) + C %.3f (%.1f%%)\n",
            ss_A, ss_G, ss_G/ss_A*100, ss_C, ss_C/ss_A*100))


# ============================================================================
#  4. CPM を計算する
# ============================================================================
#     d_CPM^2(i,j) = sum_{k=1}^{n} (c_ki - c_kj)^2
#
# C の第 i 列と第 j 列のユークリッド距離。

d_CPM2 <- matrix(0, n, n, dimnames = list(nm, nm))

for (i in 1:n) {
  for (j in 1:n) {
    if (i != j) {
      d_CPM2[i, j] <- sum((C[, i] - C[, j])^2)
    }
  }
}

CPM <- sqrt(d_CPM2)


# ============================================================================
#  5. 分解の検算
# ============================================================================
# C も歪対称かつ対角ゼロなので、次の分解が成り立つはず。
#     d_CPM^2 = 2 c_ij^2 + sum_{k != i,j} (c_ki - c_kj)^2

c2     <- C^2                                      # 直接項
third2 <- matrix(0, n, n, dimnames = list(nm, nm))  # 第三者項

for (i in 1:n) {
  for (j in 1:n) {
    if (i != j) {
      k <- setdiff(1:n, c(i, j))
      third2[i, j] <- sum((C[k, i] - C[k, j])^2)
    }
  }
}

cat("C についても分解が成立するか :",
    all(abs(d_CPM2 - (2 * c2 + third2)) < 1e-10), "\n")

share <- 2 * c2 / d_CPM2
diag(share) <- NA
cat(sprintf("直接項の寄与 : 最小 %.1f%%  最大 %.1f%%  平均 %.1f%%\n",
            100 * min(share, na.rm = TRUE), 100 * max(share, na.rm = TRUE),
            100 * mean(share, na.rm = TRUE)))


# ============================================================================
#  6. 布置を求める
# ============================================================================
# CPM は C の列ベクトル間のユークリッド距離なので、必ずユークリッド距離行列。
# したがって古典的MDSで問題ない。

fit <- cmdscale(as.dist(CPM), k = 2, eig = TRUE)
X <- fit$points
ev <- fit$eig

cat("\nCPM 2次元説明率 :", round(sum(ev[1:2]) / sum(abs(ev)) * 100, 1), "%\n")
cat("最小固有値      :", round(min(ev), 6), " （0以上ならユークリッド）\n")


# ============================================================================
#  7. 作図
# ============================================================================

df <- data.frame(country = nm, Dim1 = X[, 1], Dim2 = X[, 2])

p <- ggplot(df, aes(Dim1, Dim2, label = country)) +
  geom_hline(yintercept = 0, colour = "grey85", linewidth = 0.3) +
  geom_vline(xintercept = 0, colour = "grey85", linewidth = 0.3) +
  geom_point(size = 3.2, colour = "steelblue") +
  geom_text_repel(size = 4.2, seed = 123) +
  coord_equal() +
  labs(title = "CPM-MDS", x = "Dimension 1", y = "Dimension 2") +
  theme_minimal(base_size = 12)

print(p)


# ============================================================================
#  8. 表3のもとになる一覧
# ============================================================================

tbl <- data.frame()

for (i in 1:(n - 1)) {
  for (j in (i + 1):n) {
    tbl <- rbind(tbl, data.frame(
      pair   = paste(nm[i], nm[j], sep = "-"),
      c_abs  = round(abs(C[i, j]), 3),
      third  = round(sqrt(third2[i, j]), 3),
      CPM    = round(CPM[i, j], 3),
      share  = round(2 * c2[i, j] / d_CPM2[i, j] * 100, 1)
    ))
  }
}

print(tbl[order(-tbl$share), ], row.names = FALSE)

cat("\n勾配 φ と第1次元の相関 :", round(cor(phi, X[, 1]), 3), "\n")


# ============================================================================
#  8. 検証：勾配と循環の比を帰無基準と比べる
# ============================================================================
# 勾配成分の自由度は n-1、循環成分の自由度は (n-1)(n-2)/2。歪対称成分が
# 構造をもたない独立同分布の誤差なら、勾配の占める割合は Beta(df_G/2, df_C/2)
# に従い、n = 8 では期待値が 7/28 = 25% にとどまる。つまり「循環が4割」は
# ノイズの水準（75%）よりむしろ小さい。特筆すべきは勾配が 63% と大きいこと。

df_G    <- n - 1
df_C    <- (n - 1) * (n - 2) / 2
share_G <- ss_G / ss_A

cat("\n--- 勾配 / 循環 の帰無基準 ---\n")
cat(sprintf("  自由度       : 勾配 %d, 循環 %d\n", df_G, df_C))
cat(sprintf("  帰無期待値   : 勾配 %.1f%%, 循環 %.1f%%\n",
            df_G / (df_G + df_C) * 100, df_C / (df_G + df_C) * 100))
cat(sprintf("  観測値       : 勾配 %.1f%%, 循環 %.1f%%\n",
            share_G * 100, (1 - share_G) * 100))
cat(sprintf("  p = P(Beta(%.1f, %.1f) >= %.3f) = %.4f\n", df_G / 2, df_C / 2,
            share_G, pbeta(share_G, df_G / 2, df_C / 2, lower.tail = FALSE)))
cat(sprintf("  自由度あたり : 勾配 %.2f, 循環 %.2f\n", ss_G / df_G, ss_C / df_C))


# ============================================================================
#  9. 検証：循環成分の中身（3対象の巡回和）
# ============================================================================
# c_ij + c_jk + c_ki は、各対象に1つの値を割り当てるどの方法によっても
# 説明できない量。勾配成分 G では恒等的にゼロになる。

tri <- NULL
for (i in 1:(n - 2)) for (j in (i + 1):(n - 1)) for (k in (j + 1):n)
  tri <- rbind(tri, data.frame(triple = paste(nm[i], nm[j], nm[k], sep = "-"),
                               curl   = C[i, j] + C[j, k] + C[k, i],
                               g_curl = G[i, j] + G[j, k] + G[k, i]))

cat("\n--- 巡回和の絶対値 上位5組 ---\n")
print(head(transform(tri[order(-abs(tri$curl)), ],
                     curl = round(curl, 3), g_curl = round(g_curl, 12)), 5),
      row.names = FALSE)
cat("勾配成分 G の巡回和（最大絶対値）:", format(max(abs(tri$g_curl)), digits = 3), "\n")


# ============================================================================
#  10. 検証：CPM の古典的MDSは C の特異値分解である
# ============================================================================
# C の行和・列和がゼロなので、二重中心化グラム行列は C'C = -C^2 に厳密に
# 一致する。よって負の固有値が出ないのは定理であり、固有値が対で現れるのも
# 歪対称行列の特異値が対で現れることの帰結。

J <- diag(n) - matrix(1 / n, n, n)
cat("\n--- CPM の構造 ---\n")
cat("  B と -C^2 の最大差 :",
    format(max(abs(-0.5 * J %*% (CPM^2) %*% J + C %*% C)), digits = 3), "\n")
cat("  C の特異値（対で現れる）:", paste(round(svd(C)$d, 3), collapse = " "), "\n")
cat("  <G, C> =", format(sum(G * C), digits = 3), "（直交）\n")
